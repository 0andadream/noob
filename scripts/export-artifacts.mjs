import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const variants = [
  ["fixed", "NoobToken"],
  ["mintable", "NoobTokenMintable"],
  ["burnable", "NoobTokenBurnable"],
  ["mintableBurnable", "NoobTokenMintableBurnable"],
];

const openZeppelin = JSON.parse(
  readFileSync("node_modules/@openzeppelin/contracts/package.json", "utf8"),
).version;
const forgeVersion = execSync("forge --version", { encoding: "utf8" }).split("\n")[0].trim();

execSync("forge build", { stdio: "inherit" });

const contracts = {};
for (const [key, name] of variants) {
  const artifact = JSON.parse(readFileSync(`out/${name}.sol/${name}.json`, "utf8"));
  const bytecode = artifact.bytecode.object;
  if (!bytecode.startsWith("0x") || bytecode.length < 10) {
    throw new Error(`Unexpected bytecode for ${name}`);
  }
  contracts[key] = { abi: artifact.abi, bytecode };
}

const header = `// Generated by scripts/export-artifacts.mjs. Do not edit by hand.
// OpenZeppelin contracts ${openZeppelin}
// ${forgeVersion}
// solc 0.8.30, optimizer 200 runs, evm cancun
// Source: src/NoobToken.sol and the mintable and burnable variants.

import type { Abi, Hex } from "viem";

`;

const body = `export const erc20Artifacts = ${JSON.stringify(contracts, null, 2)} as {
  fixed: { abi: Abi; bytecode: Hex };
  mintable: { abi: Abi; bytecode: Hex };
  burnable: { abi: Abi; bytecode: Hex };
  mintableBurnable: { abi: Abi; bytecode: Hex };
};
`;

writeFileSync("lib/erc20-artifacts.ts", header + body);
console.log("Wrote lib/erc20-artifacts.ts");
